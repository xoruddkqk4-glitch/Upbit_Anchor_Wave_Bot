def api_call_with_retry(func, *args, **kwargs):
    """Google Sheets API 429 Rate Limit 발생 시 자동 대기 후 재시도"""
    delay = 10
    for i in range(5):
        try:
            return func(*args, **kwargs)
        except Exception as e:
            if "429" in str(e) or "Quota" in str(e):
                print(f"  [Google API 비율 제한 대기] {delay}초 대기 후 재시도 ({i+1}/5)...")
                time.sleep(delay)
                delay += 10
            else:
                raise e
    return func(*args, **kwargs)

